// tb_step -- THE MACHINE SINGLE-STEPS MICROINSTRUCTIONS, one at a time.
//
// This is the primitive Boot0 is built out of: the BaseBoard's loader jams a
// `CPRegToLink#`/`CPRegToIM#` pair and steps it, 475 times, to fill IM. Every
// step here is exactly one microinstruction -- `clk0'` twice, `clk1'` twice,
// `clk2'` four times, and `Stop` set again at the end -- and the jammed
// `CPRegToLink#` executes: CPReg 002A reaches Link as fd5 (the complement,
// because ContA b02's MC10159 has inverting outputs).
//
// A STEP IS AT LEAST TWO CONTROL STROBES: one carrying ClrStop+SetRun to go,
// and A FOLLOWING ONE WITHOUT ClrStop so the machine can stop again. PARC
// issues three -- DoDoradoMicroInst's tail plus BasicStopDorado --
//
//   1. ClrStop+SetRun (0x41)  release the stop latch and go
//   2. SetRun         (0x01)  ) either of these withdraws ClrStop; the second
//   3. 0              (0x00)  ) also withdraws SetRun
//
// and the sequence here is PARC's, but MEASURED: dropping (2) still steps
// correctly, so it is the FOLLOWING STROBE that matters and not its data.
// (Recorded because the first version of this comment claimed all three were
// load-bearing, and the mutation that was supposed to prove it passed.)
//
// WITH NO SECOND STROBE AT ALL the machine free-runs. `rStop` is a LEVEL out
// of ContA j02 that lasts until the next Control strobe; left asserted it
// holds the stop latch reset and the machine never stops -- measured, 26
// `clk0'` edges in a window where one step gives 2, with `Stop` still 0. That
// is the other half of `run-test`'s finding that ClrStop and SetRun must share
// a byte: sharing the byte is how you START, and letting ClrStop go is how you
// STOP again.
//
// THE FIRST STEP OUT OF A STOP IS HALF A MICROINSTRUCTION -- `clk0'` twice and
// `clk1'` not at all -- because the phase generator comes out of reset with
// `sPhase0` held and `StartCycle` cleared, so the first window is the clk0
// half only. Every step after it is whole. That is not a defect, and it is
// what PARC's own `DoIRTableInstAndNop` accounts for: it never jams an IRTable
// entry alone, and its comment says why -- "the Nop holds CPReg constant
// through T3 of the PREVIOUS instruction". The Dorado is pipelined, and an
// instruction's later phases run while the next one is in the MIR.
//
// COUNT THE CLOCKS CONTINUOUSLY. The machine runs DURING the Control strobes,
// so a window opened after the last one sees nothing at all -- which read
// exactly like a machine that had stopped dead.
//
// The manifold hold is here for the same reason it is in tb_operand: without
// it the MIR reloads from IM and there is no jam left to step.

