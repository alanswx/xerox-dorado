    zero;

    strobe(3'd2, 8'h00, 1'b0); strobe(3'd3, 8'h2A, 1'b0);   // CPReg = 002A
    jam_step(8'h30, 8'h13, 8'hEF, 8'h04, 8'h40);            // CPRegToLink#
    settle;
    $display("tb_step: jam step -- clk0' %0d clk1' %0d clk2' %0d, Stop=%b",
             n0, n1, n2, m.b_ContA.Stop);
    if (n0 !== 2)             $fatal(1, "the jam step did not run one clk0 window");
    if (m.b_ContA.Stop !== 1) $fatal(1, "the machine did not stop after the jam step");

    // Four more, each of which must be exactly ONE microinstruction.
    for (s = 0; s < 4; s = s + 1) begin
      zero;
      step_again;
      settle;
      $display("tb_step: step %0d   -- clk0' %0d clk1' %0d clk2' %0d, Stop=%b, Link[4:15]=%h",
               s + 2, n0, n1, n2, m.b_ContA.Stop, link_hi);
      if (m.b_ContA.Stop !== 1'b1)
        $fatal(1, "the machine did not stop again -- ClrStop is still asserted, so this is a free run");
      if (n0 !== 2) $fatal(1, "a step is not exactly one clk0 pulse");
      if (n1 !== 2) $fatal(1, "a step is not exactly one clk1 pulse");
      if (n2 !== 4) $fatal(1, "clk2' must run at twice clk0', so four edges to their two");
      // The jammed CPRegToLink# executed on the first whole step and Link has
      // held its value ever since -- the MIR is held, so every step repeats it.
      if (link_hi !== 12'hFD5)
        $fatal(1, "the jammed CPRegToLink# did not put CPReg into Link");
    end

    $display("tb_step: the machine single-steps microinstructions, and the jam executes.");
    $finish;
  end

