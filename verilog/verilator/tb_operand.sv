// tb_operand -- the jammed microinstruction's OPERAND reaches IM from CPReg.
//
// `writeim-test` proves the MECHANISM and the half-select and says outright
// what it does not prove: "The DATA does not come from CPReg: zeroing the
// CPReg the microinstruction is supposed to read leaves the written pattern
// unchanged." This is that missing half. It is not, in the end, anything to
// do with the FF decode -- that was already right -- but with the MIR CLOCK.
//
// WHY A JAM NEEDS THE MIR CLOCK HELD. Inside one microinstruction the order
// is: `h*clk0'` rises and the MIR loads from IM, then `clk1'` rises and ContA
// c17 latches what the FF field decodes to -- `B<-Link'`, `UseCPReg`,
// `Link<-BMux`. Coming out of a stop, clk0 is always first. So the BaseBoard's
// jam is overwritten by IM half a microinstruction before the register that
// would act on it ever clocks. MEASURED: free-running, FF goes 01111110 ->
// 11111111 at fabric cycle 206 and clk1' does not pulse until 214.
//
// WHAT HOLDS IT is on ContA c19: `h*clk0'Ca` = OR(RepeatCurC, StopMIRClk,
// preclk0'Cb). `StopMIRClk` (ContB k02) = NOR(ContB09.sil+3, StopMIRClkEn'),
// where ContB09.sil+3 (l03, an MC10121) is the IM PARITY-ERROR term and
// `StopMIRClkEn` (ContB g03) is a MANIFOLD bit. Both come off the muffler
// chain, and PARC's boot ROM sets both, once, at power-up --
// `doradomufman.masm`, in the group "invoked as a group just after the power
// supplies are up and stable":
//
//     DisableDoradoErrors  .ADR (ParityEnables+030)^4  ; all except IM parity
//                                                      ; errors disabled
//     SetMidasStopMIRClk   .ADR (MidasStopMIRClk+20)^4 ; turn on MIR debug
//                                                      ; feature
//
// So the "MIR debug feature" -- freeze the MIR on an IM parity error so the
// failing microinstruction is still there to read -- is ALSO what makes a jam
// executable: a microinstruction the BaseBoard put in the MIR did not come
// from IM and does not satisfy IM's parity, so the MIR stops and the jam
// survives its own first clock.
//
// THE MANIFOLD IS DRIVEN HERE THE WAY THE BASEBOARD DRIVES IT, twelve bits
// MSB-first into ContB's l22/l20 shift chain on `bDMuxClk'` (= ~DMuxClk),
// then a ManClk pulse. The decode checks out three ways against PARC's table
// and the test asserts all three: DMD.00-02 = 000 is the board select
// (`ControlBManifold = 0`, and it makes `UseDMDEnable'` 0); DMD.03-05 is the
// register number, 0 for ParityEnables and 7 for StopMIRClk, which is exactly
// which `ManClk.n'` k01 pulses; and DMD.06.. are the data bits, so `030` sets
// IMLHPEenable and IMRHPEenable and NONE of the other four -- PARC's comment,
// bit for bit.
//
// `DMuxData`, `DMuxClk` and `UseDMD` are FORCED because BaseBd l24 drives all
// three and `dorado_proc` has no BaseBoard. They are backplane signals a
// BaseBoard would supply, not internal state.

