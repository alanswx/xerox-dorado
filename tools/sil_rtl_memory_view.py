#!/usr/bin/env python3
"""Generate a read-only Alto memory viewer for the Verilated Sil machine.

Trace actual MSA bit planes and MemD cache RAM wiring. This is a simulator
inspection aid; it never supplies guest memory or replaces CPU execution.
"""
import argparse
from pathlib import Path
import re


def instances(path):
    return {name: (typ, dict(re.findall(r'\.(\w+)\(([^)]+)\)', body)))
            for typ, name, body in re.findall(
                r'(cell_\w+)(?:\s*#\(.*?\))?\s+(u_\w+)\s*\((.*?)\n  \);',
                path.read_text(), re.S)}


def generate(directory, obj_dir=None, flat_msa=False, storage_words=262144):
    msa_header = (obj_dir / ("Vtb_exec___024root.h" if flat_msa else "Vtb_exec_msa.h")).read_text() if obj_dir else ""
    def member(chip, bank=''):
        name = ('tb_exec__DOT__m__DOT__b_'+bank+'__DOT__' if flat_msa else '') + chip + "__DOT__mem"
        if msa_header and not re.search(r"\b" + name + r"\s*;", msa_header):
            name = "__PVT__" + name
            if not re.search(r"\b" + name + r"\s*;", msa_header):
                raise ValueError(f"Missing actual RTL memory array: {chip}")
        return name
    msa = instances(directory / 'msa.v')
    outputs = {}
    ports = {'cell_MC10176': ['p2', 'p3', 'p4', 'p13', 'p14', 'p15'],
             'cell_MC10124': ['p1', 'p2', 'p14', 'p15'],
             'cell_SN74166': ['p13'], 'cell_MK4096P_6': ['p14']}
    for name, (typ, pins) in msa.items():
        for pin in ports.get(typ, []):
            if pin in pins:
                outputs[pins[pin]] = name, pin
    planes = []
    for bit in range(16):
        name, pin = outputs[f'Sin_{bit:02d}__drv']
        pins = msa[name][1]
        name, pin = outputs[pins[dict(zip(
            ['p2', 'p3', 'p4', 'p13', 'p14', 'p15'],
            ['p5', 'p6', 'p7', 'p10', 'p11', 'p12']))[pin]]]
        pins = msa[name][1]
        name, pin = outputs[pins[{'p1': 'p7', 'p2': 'p5',
                                  'p15': 'p10', 'p14': 'p11'}[pin]]]
        typ, pins = msa[name]
        assert typ == 'cell_SN74166', (name, typ)
        planes.append([outputs[pins[k]][0] for k in
                       ['p2', 'p3', 'p4', 'p5', 'p10', 'p11', 'p12', 'p14']])
    lines = ['// Generated by tools/sil_rtl_memory_view.py. Read-only RTL view.',
             '#pragma once', '#include "Vtb_exec__Syms.h"', '#include <cstdint>',
             'static uint16_t rtl_dram_word(Vtb_exec__Syms* s, unsigned va) {',
             ('auto* r=&s->TOP;' if flat_msa else 'auto& ms = (va & 1) ? s->TOP__tb_exec__DOT__m__DOT__b_msaOdd : s->TOP__tb_exec__DOT__m__DOT__b_msa;'),
             'unsigned rp=va>>8, row=0, col=0;']
    for i, bit in enumerate([9, 7, 6, 5, 4, 3, 2]):
        lines.append(f'row |= (1 ^ ((rp >> {bit}) & 1)) << {i};')
    for i, bit in enumerate([8, 1, 0]):
        lines.append(f'col |= (1 ^ ((rp >> {bit}) & 1)) << {i};')
    for i, bit in enumerate([7, 6, 5, 4], 3):
        lines.append(f'col |= (1 ^ ((va >> {bit}) & 1)) << {i};')
    lines += ['unsigned a=(row<<7)|col;', 'switch (7-((va&15)/2)) {']
    for stage in range(8):
        terms = []
        for bit in range(16):
            chip = planes[bit][stage]
            inverted = '_p_' in msa[chip][1].get('p10', '')
            addr = f'a ^ {16383 if inverted else 0}'
            if storage_words < 262144:
                lowmask = 63 if storage_words == 65536 else 127
                shift = 1 if storage_words == 65536 else 0
                addr = f'((({addr}) >> 8) << {6 if storage_words == 65536 else 7}) | ((({addr}) >> {shift}) & {lowmask})'
            value = (f'((va&1) ? r->{member(chip,"msaOdd")}[{addr}] : r->{member(chip,"msa")}[{addr}])' if flat_msa else f'ms.{member(chip)}[{addr}]')
            terms.append(f'(({value} & 1) << {15-bit})')
        lines.append(f'case {stage}: return ' + ' | '.join(terms) + ';')
    lines += ['}', 'return 0;', '}']

    memd = instances(directory / 'MemD-Rev-Ca.v')
    eq = {}
    for _, (typ, pins) in memd.items():
        def link(out, ins, inv=0):
            if out in pins:
                eq[pins[out]] = tuple(pins.get(i, "1'b0") for i in ins), inv
        if typ == 'cell_MC10231':
            for out, inp, inv in [('p2', 'p7', 0), ('p3', 'p7', 1),
                                  ('p15', 'p10', 0), ('p14', 'p10', 1)]:
                link(out, [inp], inv)
        if typ == 'cell_MC10210':
            for out in ['p2', 'p3', 'p4']: link(out, ['p5', 'p6', 'p7'])
            for out in ['p12', 'p13', 'p14']: link(out, ['p9', 'p10', 'p11'])
        if typ == 'cell_MC10101':
            for out, ins, inv in [('p2', ['p4', 'p12'], 1), ('p5', ['p4', 'p12'], 0),
                                  ('p3', ['p7', 'p12'], 1), ('p6', ['p7', 'p12'], 0),
                                  ('p14', ['p10', 'p12'], 1), ('p11', ['p10', 'p12'], 0),
                                  ('p15', ['p13', 'p12'], 1), ('p9', ['p13', 'p12'], 0)]:
                link(out, ins, inv)
    env = {f'dDad_{i:02d}': f'((row >> {9-i}) & 1)' for i in range(2, 10)}
    env.update({'Dad_00': '(way >> 1)', 'Dad_01': '(way & 1)',
                'MemD03_sil_pl_5': '0', 'MemD03_sil_pl_6': '0'})
    env.update({f'Dad{b}_{i:02d}{suffix}': f'((word >> {13-i}) & 1)'
                for b in range(2) for i in range(10, 13) for suffix in 'abc'})
    def expr(net):
        if net in env: return env[net]
        if net.startswith(('GND', 'VEE')) or net == "1'b0": return '0'
        if net == "1'b1": return '1'
        ins, inv = eq[net]
        body = '(' + ' | '.join(expr(i) for i in ins) + ')'
        return f'({body} ^ 1)' if inv else body
    lines += ['static uint16_t rtl_cache_word(Vtb_exec___024root* r, unsigned way, unsigned row, unsigned word) {',
              'unsigned v=0;']
    for chip, (typ, pins) in memd.items():
        if typ != 'cell_F10470': continue
        match = re.fullmatch(r'D([01])in_(\d+)', pins['p17'])
        if not match or int(match[2]) > 15: continue
        bank, bit = map(int, match.groups())
        addr = '(' + ' | '.join(f'({expr(pins[pin])} << {11-i})'
                for i, pin in enumerate(['p2','p3','p4','p5','p6','p7','p8','p10','p11','p12','p13','p14'])) + ')'
        cppchip = chip.replace('__h__m_', '___05Fh___05Fm_')
        lines.append(f'if ((word&1)=={bank} && !({expr(pins["p16"])})) v |= (r->tb_exec__DOT__m__DOT__b_MemD__DOT__{cppchip}__DOT__mem[{addr}] & 1) << {15-bit};')
    lines += ['return v;', '}',
              'static uint16_t rtl_visible_word(Vtb_exec__Syms* s, unsigned va) {',
              'auto* r=&s->TOP; unsigned row=(va>>4)&255;']
    for way, col in enumerate('abcd'):
        lines += ['{', f'unsigned tr=row ^ {255 if way&1 else 0};',
                  f'if (!(r->tb_exec__DOT__m__DOT__b_MemC__DOT__u_{col}08__DOT__mem[tr] & 2)) {{',
                  'unsigned tag=0;']
        for k, chip in enumerate(['10', '12', '18', '20']):
            for j in range(4):
                if 16-4*k+j >= 5:
                    lines.append(f'tag |= ((r->tb_exec__DOT__m__DOT__b_MemC__DOT__u_{col}{chip}__DOT__mem[tr] >> {j}) & 1) << {31-(16-4*k+j)};')
        lines += [f'if ((tag|(row<<4)) == (va&~15u)) return rtl_cache_word(r,{way},row,va&15);', '}', '}']
    lines += ['return rtl_dram_word(s,va);', '}']
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--generated', type=Path, default=Path('verilog/generated'))
    ap.add_argument('-o', '--output', required=True, type=Path)
    ap.add_argument('--obj-dir', type=Path)
    ap.add_argument('--flat-msa', action='store_true', help='MSA cells are flattened into the root of a specialized checkpoint model')
    ap.add_argument('--storage-words', type=int, choices=[65536, 131072, 262144], default=262144)
    args = ap.parse_args()
    args.output.write_text(generate(args.generated, args.obj_dir, args.flat_msa, args.storage_words))
